"""Numbers for the storm-drag RNAAS note, generated from research/results/atlas/.

Writes research/results/rnaas_atlas/numbers.tex (LaTeX macros). Nothing is typed by hand.
Run: python -m research.figures.rnaas_atlas
"""

from __future__ import annotations

import datetime
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RES = ROOT / "research" / "results" / "atlas"
OUT = ROOT / "research" / "results" / "rnaas_atlas"

LETTERS = {"400": "Four", "450": "FourFifty", "500": "Five", "550": "FiveFifty", "600": "Six"}


def fmt_int(n: int) -> str:
    return f"{n:,}".replace(",", "{,}")


def macros(tag: str, d: dict) -> list[str]:
    m = []
    put = lambda k, v: m.append(f"\\newcommand{{\\{tag}{k}}}{{{v}}}")
    t0 = datetime.datetime.fromisoformat(d["t0"])
    put("Onset", f"{t0.day} {t0:%B %Y}, {t0:%H:%M}~UT")
    put("NSets", fmt_int(d["n_element_sets"]))
    put("NPrimary", fmt_int(d["n_primary_objects"]))
    put("NPayload", fmt_int(d["n_secondary_objects"]))
    put("NQuiet", d["n_quiet_days"])
    peaks = {s: v["peak_R"] for s, v in d["shells"].items()}
    put("PeakMin", f"{min(peaks.values()):.1f}")
    put("PeakMax", f"{max(peaks.values()):.1f}")
    put("NShells", len(peaks))
    for s, v in d["shells"].items():
        put(f"Peak{LETTERS[s]}", f"{v['peak_R']:.1f}")
        put(f"Lag{LETTERS[s]}", f"{v['peak_lag_h']:g}")
    lags = sorted({v["peak_lag_h"] for v in d["shells"].values()})
    put("Lags", ", ".join(f"{x:g}" for x in lags))
    put("Rho", f"{d['HA2_altitude']['spearman_rho']:.2f}")
    put("HAOne", "passed" if d["HA1_timing"]["pass"] else "failed")
    put("HATwo", "passed" if d["HA2_altitude"]["pass"] else "failed")
    put("HAThree", "passed" if d["HA3_detectability"]["pass"] else "failed")
    put("HAFour", "passed" if d["HA4_payload_not_larger"]["pass"] else "failed")
    put("DetectFrac", f"{100 * d['HA3_detectability']['fraction']:.0f}")
    put("DetectN", d["HA3_detectability"]["n_shells"])
    hx = d.get("HX_thrust_masking")
    if hx:
        c, p = hx["peak_constellation"], hx["peak_primary"]
        put("ConstMaxRatio", f"{max(c[s] / p[s] for s in c):.1f}")
        put("NConst", fmt_int(hx["n_constellation_objects"]))
    return m


def main() -> None:
    may = json.loads((RES / "atlas_summary.json").read_text())
    octo = json.loads((RES / "oct2024" / "atlas_summary.json").read_text())
    lines = ["% GENERATED by research/figures/rnaas_atlas.py -- do not edit"]
    lines += macros("May", may) + macros("Oct", octo)
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "numbers.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {len(lines) - 1} macros to {OUT / 'numbers.tex'}")


if __name__ == "__main__":
    main()
